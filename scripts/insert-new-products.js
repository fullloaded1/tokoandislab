async function main() {
  console.log(`Starting insert of ${newProducts.length} products...\n`);
  let created = 0;
  let skipped = 0;

  for (const p of newProducts) {
    const existing = await prisma.product.findUnique({ where: { slug: p.slug } });
    if (existing) {
      console.log(`  SKIP (exists): ${p.name}`);
      skipped++;
      continue;
    }

    await prisma.product.create({
      data: {
        slug: p.slug,
        name: p.name,
        category: p.category,
        categoryLabel: p.categoryLabel,
        brand: p.brand,
        model: p.model,
        subcategory: p.subcategory,
        image: p.image,
        description: p.description,
        price: p.price,
        isReadyStock: p.isReadyStock,
        isRequestPricing: false,
        specs: {
          create: p.specs,
        },
        variants: {
          create: [{
            sku: p.variantSku,
            name: p.variantName,
            price: p.price,
            stock: p.variantStock,
            sortOrder: 0,
          }],
        },
      },
    });
    console.log(`  OK: ${p.name} — Rp ${p.price.toLocaleString('id-ID')}`);
    created++;
  }

  console.log(`\n=== DONE ===`);
  console.log(`Created : ${created}`);
  console.log(`Skipped : ${skipped}`);
  console.log(`Total   : ${newProducts.length}`);
}

main()
  .catch((e) => {
    console.error('Error:', e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
